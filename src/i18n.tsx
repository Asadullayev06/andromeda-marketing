const DICTS: Record<Lang, Dict> = { en, ru, uz };

interface I18nCtx { lang: Lang; setLang: (l: Lang) => void; t: (key: string) => string; }
const Ctx = createContext<I18nCtx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem(LANG_KEY) as Lang | null;
      if (saved && (saved === 'uz' || saved === 'ru' || saved === 'en')) return saved;
    } catch { /* ignore */ }
    return 'uz';
  });
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const value = useMemo<I18nCtx>(() => ({
    lang,
    setLang: (l) => { setLangState(l); try { localStorage.setItem(LANG_KEY, l); } catch { /* ignore */ } },
    t: (key) => DICTS[lang][key] ?? en[key] ?? key,
  }), [lang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useLang(): I18nCtx {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error('useLang must be used within I18nProvider');
  return ctx;
}
